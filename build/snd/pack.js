/* Packs the 8 kHz mu-law WAV files in this folder into build/src/77_sounds.js
   as base64 strings of the raw mu-law bytes, so the artifact stays a single
   file. Run after adding or replacing a sound: node build/snd/pack.js

   apollo11.wav: "That's one small step for man, one giant leap for mankind",
   Neil Armstrong, 20 July 1969. NASA recording, public domain; taken from
   Wikimedia Commons, File:Neil_Armstrong_small_step.wav, the two phrases cut
   at 15.3-17.8 s and 20.6-24.05 s, band-limited to 300-3400 Hz and
   resampled to 8 kHz mu-law with ffmpeg. */
const fs = require('fs'), path = require('path');
function data(buf){
  if(buf.toString('ascii', 0, 4) !== 'RIFF') throw new Error('not a WAV file');
  let p = 12, fmt = null;
  while(p < buf.length){
    const id = buf.toString('ascii', p, p+4), n = buf.readUInt32LE(p+4);
    if(id === 'fmt ') fmt = { code: buf.readUInt16LE(p+8), ch: buf.readUInt16LE(p+10), sr: buf.readUInt32LE(p+12) };
    if(id === 'data'){
      if(!fmt || fmt.code !== 7 || fmt.ch !== 1 || fmt.sr !== 8000) throw new Error('need mono 8 kHz mu-law');
      return buf.subarray(p+8, p+8+n);
    }
    p += 8 + n + (n & 1);
  }
  throw new Error('no data chunk');
}
const files = fs.readdirSync(__dirname).filter(f => f.endsWith('.wav')).sort();
const rows = files.map(f => `  ${JSON.stringify(f.replace(/\.wav$/, ''))}: '${
  data(fs.readFileSync(path.join(__dirname, f))).toString('base64')}'`);
const out = `/* generated by build/snd/pack.js; do not edit */\nconst SND = {\n${rows.join(',\n')}\n};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', '77_sounds.js'), out);
console.log('packed', files.length, 'sounds,', (out.length / 1024).toFixed(0), 'KB');
